package com.banking.core.domain.entity;

import com.banking.core.domain.enums.AccountStatus;
import com.banking.core.domain.enums.AccountType;
import jakarta.persistence.*;
import lombok.*;
import org.springframework.data.annotation.CreatedDate;
import org.springframework.data.annotation.LastModifiedDate;
import org.springframework.data.jpa.domain.support.AuditingEntityListener;

import java.math.BigDecimal;
import java.time.Instant;
import java.util.List;
import java.util.UUID;

/**
 * JPA entity representing a bank account owned by a {@link User}.
 *
 * <h3>Balance Precision</h3>
 * Balance is modelled as {@link BigDecimal} and stored as {@code NUMERIC(19,4)}.
 * This guarantees exact decimal arithmetic — using {@code double} or
 * {@code float} here would be an unacceptable correctness bug in a financial system.
 *
 * <h3>Non-negative Balance Guarantee</h3>
 * Enforced at <em>two</em> independent layers:
 * <ol>
 *   <li><b>Database</b>: {@code CHECK (balance >= 0)} constraint in Flyway DDL.</li>
 *   <li><b>Application</b>: Service layer throws {@code InsufficientFundsException}
 *       before attempting a debit.</li>
 * </ol>
 * Both layers are intentional. Defence-in-depth: a bug in one layer should not
 * result in a negative balance.
 *
 * <h3>Concurrency</h3>
 * In Phase 4 the transfer service will acquire a {@code PESSIMISTIC_WRITE}
 * lock on this entity before mutating {@code balance}, ensuring that
 * concurrent transfers on the same account are serialised at the DB level.
 */
@Entity
@Table(
    name = "accounts",
    uniqueConstraints = {
        @UniqueConstraint(name = "uq_accounts_number", columnNames = "account_number")
    }
)
@EntityListeners(AuditingEntityListener.class)
@Getter
@Setter
@Builder
@NoArgsConstructor
@AllArgsConstructor
public class Account {

    @Id
    @GeneratedValue(strategy = GenerationType.UUID)
    @Column(name = "id", updatable = false, nullable = false)
    private UUID id;

    /**
     * Owning user. Many-to-one because one user may have multiple accounts.
     * We use LAZY loading: the User is not fetched unless explicitly accessed.
     * Foreign key: {@code accounts.user_id → users.id}.
     */
    @ManyToOne(fetch = FetchType.LAZY, optional = false)
    @JoinColumn(
        name = "user_id",
        nullable = false,
        foreignKey = @ForeignKey(name = "fk_accounts_users")
    )
    private User user;

    /**
     * Human-readable, unique account identifier (e.g., "100000000001").
     * Generated by the service layer (sequential or random) — not a UUID
     * so it is easier for customers to reference in correspondence.
     */
    @Column(name = "account_number", nullable = false, length = 20, updatable = false)
    private String accountNumber;

    @Enumerated(EnumType.STRING)
    @Column(name = "account_type", nullable = false, length = 30)
    @Builder.Default
    private AccountType accountType = AccountType.SAVINGS;

    @Enumerated(EnumType.STRING)
    @Column(name = "status", nullable = false, length = 20)
    @Builder.Default
    private AccountStatus status = AccountStatus.ACTIVE;

    /**
     * Current account balance.
     * <p>
     * {@code precision=19, scale=4} matches the DB column {@code NUMERIC(19,4)}.
     * The service layer must NEVER read this value and then write it back without
     * acquiring a lock first (Phase 4 — pessimistic locking).
     */
    @Column(name = "balance", nullable = false, precision = 19, scale = 4)
    @Builder.Default
    private BigDecimal balance = BigDecimal.ZERO;

    /**
     * ISO 4217 currency code (e.g., "USD", "EUR", "INR").
     * Phase 3 will add cross-currency validation logic.
     */
    @Column(name = "currency", nullable = false, length = 3)
    @Builder.Default
    private String currency = "USD";

    // ── Auditing ──────────────────────────────────────────────────────────

    @CreatedDate
    @Column(name = "created_at", nullable = false, updatable = false)
    private Instant createdAt;

    @LastModifiedDate
    @Column(name = "updated_at", nullable = false)
    private Instant updatedAt;

    // ── Relationship ──────────────────────────────────────────────────────

    @OneToMany(mappedBy = "senderAccount", fetch = FetchType.LAZY)
    private List<Transaction> sentTransactions;

    @OneToMany(mappedBy = "receiverAccount", fetch = FetchType.LAZY)
    private List<Transaction> receivedTransactions;

    // ── Domain Methods ────────────────────────────────────────────────────

    /**
     * Returns {@code true} if this account can participate in a transfer.
     * An account must be ACTIVE and belong to the same currency family.
     */
    public boolean isTransferable() {
        return AccountStatus.ACTIVE.equals(this.status);
    }

    // ── equals / hashCode ─────────────────────────────────────────────────

    @Override
    public boolean equals(Object o) {
        if (this == o) return true;
        if (!(o instanceof Account other)) return false;
        return id != null && id.equals(other.id);
    }

    @Override
    public int hashCode() {
        return getClass().hashCode();
    }

    @Override
    public String toString() {
        return "Account{id=" + id +
               ", accountNumber='" + accountNumber + "'" +
               ", status=" + status +
               ", balance=" + balance +
               ", currency='" + currency + "'}";
    }
}

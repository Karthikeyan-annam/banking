package com.banking.core.domain.entity;

import com.banking.core.domain.enums.TransactionStatus;
import com.banking.core.domain.enums.TransactionType;
import jakarta.persistence.*;
import lombok.*;
import org.springframework.data.annotation.CreatedDate;
import org.springframework.data.annotation.LastModifiedDate;
import org.springframework.data.jpa.domain.support.AuditingEntityListener;

import java.math.BigDecimal;
import java.time.Instant;
import java.util.UUID;

/**
 * JPA entity representing one leg of a financial event in the ledger.
 *
 * <h3>Double-Entry Bookkeeping</h3>
 * For a P2P transfer, the service layer inserts TWO {@code Transaction} records
 * within a single {@code @Transactional} scope:
 * <pre>
 *   txn1: type=DEBIT,  senderAccount=A,    receiverAccount=B,  amount=100
 *   txn2: type=CREDIT, senderAccount=A,    receiverAccount=B,  amount=100
 * </pre>
 * Both rows share the same {@code referenceId} UUID so they can be correlated.
 *
 * <h3>Immutability</h3>
 * Transaction rows are effectively immutable once written.  {@code status}
 * is the ONLY column that may be updated (PENDING → COMPLETED or FAILED).
 * No amount or account field should ever be changed after insertion.
 *
 * <h3>Audit Trail</h3>
 * {@code initiatedByIp} captures the caller's IP address for fraud/compliance
 * purposes.  This is populated by the service from the HTTP request context.
 */
@Entity
@Table(
    name = "transactions",
    indexes = {
        @Index(name = "idx_transactions_sender",
               columnList = "sender_account_id, created_at DESC"),
        @Index(name = "idx_transactions_receiver",
               columnList = "receiver_account_id, created_at DESC"),
        @Index(name = "idx_transactions_ref",    columnList = "reference_id"),
        @Index(name = "idx_transactions_status", columnList = "status"),
        @Index(name = "idx_transactions_created",columnList = "created_at DESC")
    }
)
@EntityListeners(AuditingEntityListener.class)
@Getter
@Setter
@Builder
@NoArgsConstructor
@AllArgsConstructor
public class Transaction {

    @Id
    @GeneratedValue(strategy = GenerationType.UUID)
    @Column(name = "id", updatable = false, nullable = false)
    private UUID id;

    /**
     * Groups the debit + credit legs of a single logical transfer.
     * Both rows written for a P2P transfer share this UUID.
     * Generated by the service before inserting either leg.
     */
    @Column(name = "reference_id", nullable = false, updatable = false)
    private UUID referenceId;

    /**
     * The account debited (money leaves).
     * NULL for external deposit events where there is no internal sender.
     */
    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(
        name = "sender_account_id",
        foreignKey = @ForeignKey(name = "fk_transactions_sender")
    )
    private Account senderAccount;

    /**
     * The account credited (money arrives).
     * NULL for external withdrawal events where there is no internal receiver.
     */
    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(
        name = "receiver_account_id",
        foreignKey = @ForeignKey(name = "fk_transactions_receiver")
    )
    private Account receiverAccount;

    @Enumerated(EnumType.STRING)
    @Column(name = "transaction_type", nullable = false, length = 20, updatable = false)
    private TransactionType transactionType;

    /**
     * Transfer amount.
     * <p>
     * Stored as {@code NUMERIC(19,4)} — exact decimal; no floating-point rounding.
     * Enforced positive by DB CHECK constraint {@code chk_transactions_amount_positive}.
     */
    @Column(name = "amount", nullable = false, precision = 19, scale = 4, updatable = false)
    private BigDecimal amount;

    @Column(name = "currency", nullable = false, length = 3, updatable = false)
    @Builder.Default
    private String currency = "USD";

    /**
     * Current processing state.
     * This is the ONLY mutable field after initial insertion.
     */
    @Enumerated(EnumType.STRING)
    @Column(name = "status", nullable = false, length = 20)
    @Builder.Default
    private TransactionStatus status = TransactionStatus.PENDING;

    /**
     * Human-readable note (e.g., "Rent payment for November").
     * Optional; max 500 chars.
     */
    @Column(name = "description", length = 500, updatable = false)
    private String description;

    /**
     * IPv4/IPv6 address of the HTTP client who initiated this transaction.
     * Used for fraud detection and regulatory audit trails.
     * Max 45 chars supports full IPv6 representation.
     */
    @Column(name = "initiated_by_ip", length = 45, updatable = false)
    private String initiatedByIp;

    // ── Auditing ──────────────────────────────────────────────────────────

    @CreatedDate
    @Column(name = "created_at", nullable = false, updatable = false)
    private Instant createdAt;

    @LastModifiedDate
    @Column(name = "updated_at", nullable = false)
    private Instant updatedAt;

    // ── equals / hashCode ─────────────────────────────────────────────────

    @Override
    public boolean equals(Object o) {
        if (this == o) return true;
        if (!(o instanceof Transaction other)) return false;
        return id != null && id.equals(other.id);
    }

    @Override
    public int hashCode() {
        return getClass().hashCode();
    }

    @Override
    public String toString() {
        return "Transaction{id=" + id +
               ", referenceId=" + referenceId +
               ", type=" + transactionType +
               ", amount=" + amount +
               ", currency='" + currency + "'" +
               ", status=" + status + "}";
    }
}
